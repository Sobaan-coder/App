// Concatenates the migrations into supabase/setup.sql so a hosted project can be set up
// by pasting a single file into the Supabase SQL editor. Run: npm run db:bundle
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const header = `-- Study OS: complete database setup (generated by \`npm run db:bundle\` - do not edit).
-- Paste into Supabase -> SQL Editor -> New query, then Run. Includes: ${files.join(", ")}\n`;
const body = files.map((f) => `\n-- ===== ${f} =====\n${readFileSync(join(dir, f), "utf8").trimEnd()}\n`).join("");
writeFileSync("supabase/setup.sql", header + body);
console.log(`supabase/setup.sql written from ${files.length} migrations`);
